#!/usr/bin/env node
// Refresh the bundled fallback snapshot of zoebnomi.com (src/data/snapshot.ts).
// The tools read the site live; this snapshot is only what they use when the
// site does not answer. Uses the same cleaning as the live path (src/site.ts).
//
// Usage: npm run snapshot

import { writeFileSync } from 'node:fs';
import { PAGES, SITE, clean } from '../src/site.ts';

const out: Record<string, { url: string; text: string }> = {};
for (const [key, path] of Object.entries(PAGES)) {
  const res = await fetch(SITE + path, { headers: { 'user-agent': 'zoebnomi-mcp snapshot' } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  out[key] = { url: SITE + path, text: clean(key, await res.text()) };
}

const fetched = new Date().toISOString().slice(0, 10);
const src =
  '// Generated by scripts/snapshot-site.ts. Do not edit by hand.\n' +
  '// Fallback copy of zoebnomi.com, cleaned like the live path: en/em dashes and minus\n' +
  '// signs folded to "-"; contact, booking and location lines removed.\n\n' +
  `export const SNAPSHOT_DATE = ${JSON.stringify(fetched)};\n\n` +
  `export const SNAPSHOT: Record<string, { url: string; text: string }> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL('../src/data/snapshot.ts', import.meta.url), src);
console.log(`snapshot ${fetched}: ${Object.entries(out).map(([k, v]) => `${k} ${v.text.length} chars`).join(', ')}`);
